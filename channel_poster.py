def slots_since_epoch(today: date) -> int:
    if today < EPOCH:
        return 0
    count = 0
    d = EPOCH
    while d < today:
        if d.weekday() in POST_WEEKDAYS:
            count += 1
        d += timedelta(days=1)
    return count


async def main() -> None:
    if not BOT_TOKEN:
        raise RuntimeError("Не задан BOT_TOKEN в переменных окружения")

    today = date.today()
    force = os.environ.get("FORCE_POST", "").lower() in ("1", "true", "yes")
    if not force and today.weekday() not in POST_WEEKDAYS:
        logger.info("Сегодня не день публикации — выхожу без действий")
        return

    index = slots_since_epoch(today) % len(POSTS)
    post = POSTS[index]

    reply_markup = None
    if post.get("button"):
        label, url = post["button"]
        reply_markup = InlineKeyboardMarkup([[InlineKeyboardButton(label, url=url)]])

    bot = Bot(token=BOT_TOKEN)
    await bot.send_message(
        chat_id=CHANNEL_ID,
        text=post["text"],
        parse_mode=ParseMode.HTML,
        reply_markup=reply_markup,
    )
    logger.info(f"Опубликован пост №{index} в {CHANNEL_ID}")


if __name__ == "__main__":
    asyncio.run(main())
